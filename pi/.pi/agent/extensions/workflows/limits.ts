import assert from "node:assert/strict";

export const AGENT_COUNT_MAX = 64;
export const AGENT_DEFINITION_BYTES_MAX = 16 * 1024;
export const AGENT_KILL_SETTLE_MS = 2 * 1000;
export const AGENT_DIRECTORY_ENTRY_COUNT_MAX = 256;
export const AGENT_DESCRIPTION_BYTES_MAX = 512;
export const AGENT_NAME_BYTES_MAX = 64;
export const AGENT_OUTPUT_BYTES_MAX = 50 * 1024;
export const AGENT_RESULT_EXIT_GRACE_MS = 2 * 1000;
export const AGENT_TASK_BYTES_MAX = 64 * 1024;
export const AGENT_TOOL_COUNT_MAX = 64;
export const AGENT_TOOL_NAME_BYTES_MAX = 128;
export const AGENT_TERMINATE_GRACE_MS = 4 * 1000;
export const AGENT_TIMEOUT_MS = 20 * 60 * 1000;
export const AGENT_USAGE_COST_MAX = 1_000_000;
export const AGENT_USAGE_COUNT_MAX = 1_000_000_000;
export const DEPENDENCY_OUTPUT_BYTES_MAX = 48 * 1024;
export const JOB_DIRECTORY_SCAN_COUNT_MAX = 256;
export const JOB_LAUNCH_LEASE_ATTEMPT_COUNT_MAX = 64;
export const JOB_LAUNCH_LEASE_RECHECK_MS = 100;
export const JOB_LIST_COUNT_MAX = 20;
export const JOB_NOTIFICATION_BYTES_MAX = 160;
export const JOB_REQUEST_BYTES_MAX = 2 * 1024 * 1024;
export const JOB_RETENTION_COUNT_MAX = 64;
export const JOB_LIVENESS_HANDSHAKE_BYTES_MAX = 256;
export const JOB_LIVENESS_HANDSHAKE_TIMEOUT_MS = 2 * 1000;
export const JOB_LIVENESS_OBSERVER_COUNT_MAX = 16;
export const JOB_LIVENESS_SOCKET_PATH_BYTES_MAX = 100;
export const JOB_RESULT_BYTES_MAX = AGENT_OUTPUT_BYTES_MAX + 64;
export const JOB_START_TIMEOUT_MS = 5 * 1000;
export const JOB_WIDGET_LINE_COUNT_MAX = 20;
export const JOB_WIDGET_NODE_COUNT_MAX = 4;
export const JOB_STATE_BYTES_MAX = 1024 * 1024;
export const JOB_TELEMETRY_BYTES_MAX = 256 * 1024;
export const JSONL_RECORD_BYTES_MAX = 4 * 1024 * 1024;
export const JSONL_RECORD_COUNT_MAX = 100_000;
export const PROCESS_DIRECTORY_ENTRY_COUNT_MAX = 1_000_000;
export const PROCESS_METADATA_BYTES_MAX = 1024 * 1024;
export const PROCESS_GROUP_DRAIN_PASS_COUNT_MAX = 3;
export const STDERR_BYTES_MAX = 128 * 1024;
export const TERMINATE_GRACE_MS = 5 * 1000;
export const WORKFLOW_CONCURRENCY_MAX = 5;
export const WORKFLOW_FAN_OUT_MAX = 16;
export const WORKFLOW_NODE_COUNT_MAX = 64;
export const WORKFLOW_NODE_TASK_BYTES_MAX = 8 * 1024;
export const WORKFLOW_TIMEOUT_MS = 2 * 60 * 60 * 1000;
export const WORKFLOW_TOOL_OUTPUT_BYTES_MAX = 50 * 1024;
export const WORKFLOW_USAGE_COST_MAX =
	AGENT_USAGE_COST_MAX * (WORKFLOW_NODE_COUNT_MAX + 1);
export const WORKFLOW_USAGE_COUNT_MAX =
	AGENT_USAGE_COUNT_MAX * (WORKFLOW_NODE_COUNT_MAX + 1);
export const WRITER_OWNER_BYTES_MAX = 256;

export function assertLimitInvariants(): void {
	assert(AGENT_COUNT_MAX > 0);
	assert(AGENT_DEFINITION_BYTES_MAX > AGENT_DESCRIPTION_BYTES_MAX);
	assert(AGENT_KILL_SETTLE_MS > 0);
	assert(AGENT_KILL_SETTLE_MS < AGENT_TERMINATE_GRACE_MS);
	assert(AGENT_DIRECTORY_ENTRY_COUNT_MAX > AGENT_COUNT_MAX);
	assert(AGENT_DEFINITION_BYTES_MAX > AGENT_NAME_BYTES_MAX);
	assert(AGENT_OUTPUT_BYTES_MAX > 0);
	assert(AGENT_RESULT_EXIT_GRACE_MS > 0);
	assert(AGENT_RESULT_EXIT_GRACE_MS < AGENT_TERMINATE_GRACE_MS);
	assert(AGENT_TASK_BYTES_MAX > AGENT_OUTPUT_BYTES_MAX);
	assert(AGENT_TOOL_COUNT_MAX > 0);
	assert(AGENT_TOOL_NAME_BYTES_MAX > 0);
	assert(AGENT_TERMINATE_GRACE_MS < TERMINATE_GRACE_MS);
	assert(AGENT_TIMEOUT_MS > TERMINATE_GRACE_MS);
	assert(AGENT_USAGE_COST_MAX > 0);
	assert(AGENT_USAGE_COUNT_MAX > 0);
	assert(DEPENDENCY_OUTPUT_BYTES_MAX < AGENT_TASK_BYTES_MAX);
	assert(JOB_LAUNCH_LEASE_ATTEMPT_COUNT_MAX > 0);
	assert(JOB_LAUNCH_LEASE_RECHECK_MS > 0);
	assert(JOB_LAUNCH_LEASE_RECHECK_MS < JOB_START_TIMEOUT_MS);
	assert(JOB_LIST_COUNT_MAX > 0);
	assert(JOB_NOTIFICATION_BYTES_MAX > 0);
	assert(JOB_REQUEST_BYTES_MAX > JOB_STATE_BYTES_MAX);
	assert(JOB_RETENTION_COUNT_MAX >= JOB_LIST_COUNT_MAX);
	assert(JOB_DIRECTORY_SCAN_COUNT_MAX > JOB_RETENTION_COUNT_MAX);
	assert(JOB_LIVENESS_HANDSHAKE_BYTES_MAX > 0);
	assert(JOB_LIVENESS_HANDSHAKE_TIMEOUT_MS > 0);
	assert(JOB_LIVENESS_HANDSHAKE_TIMEOUT_MS <= JOB_START_TIMEOUT_MS);
	assert(JOB_LIVENESS_OBSERVER_COUNT_MAX > 0);
	assert(JOB_LIVENESS_SOCKET_PATH_BYTES_MAX > 0);
	assert(JOB_LIVENESS_SOCKET_PATH_BYTES_MAX <= 107);
	assert(JOB_RESULT_BYTES_MAX > AGENT_OUTPUT_BYTES_MAX);
	assert(JOB_STATE_BYTES_MAX > AGENT_OUTPUT_BYTES_MAX);
	assert(JOB_TELEMETRY_BYTES_MAX > AGENT_OUTPUT_BYTES_MAX);
	assert(JOB_TELEMETRY_BYTES_MAX < JOB_STATE_BYTES_MAX);
	assert(JOB_WIDGET_LINE_COUNT_MAX > JOB_WIDGET_NODE_COUNT_MAX);
	assert(JOB_WIDGET_NODE_COUNT_MAX > 0);
	assert(JSONL_RECORD_BYTES_MAX > AGENT_OUTPUT_BYTES_MAX);
	assert(JSONL_RECORD_COUNT_MAX > 0);
	assert(PROCESS_DIRECTORY_ENTRY_COUNT_MAX > 0);
	assert(PROCESS_METADATA_BYTES_MAX > 0);
	assert(PROCESS_GROUP_DRAIN_PASS_COUNT_MAX > 0);
	assert(STDERR_BYTES_MAX > AGENT_OUTPUT_BYTES_MAX);
	assert(WORKFLOW_CONCURRENCY_MAX > 0);
	assert(WORKFLOW_FAN_OUT_MAX >= WORKFLOW_CONCURRENCY_MAX);
	assert(WORKFLOW_NODE_COUNT_MAX >= WORKFLOW_FAN_OUT_MAX);
	assert(WORKFLOW_NODE_TASK_BYTES_MAX < DEPENDENCY_OUTPUT_BYTES_MAX);
	assert(WORKFLOW_TIMEOUT_MS > AGENT_TIMEOUT_MS);
	assert(WORKFLOW_TOOL_OUTPUT_BYTES_MAX <= AGENT_OUTPUT_BYTES_MAX);
	assert(WORKFLOW_USAGE_COST_MAX > AGENT_USAGE_COST_MAX);
	assert(Number.isSafeInteger(WORKFLOW_USAGE_COST_MAX));
	assert(WORKFLOW_USAGE_COUNT_MAX > AGENT_USAGE_COUNT_MAX);
	assert(Number.isSafeInteger(WORKFLOW_USAGE_COUNT_MAX));
	assert(WRITER_OWNER_BYTES_MAX > AGENT_NAME_BYTES_MAX);
}
